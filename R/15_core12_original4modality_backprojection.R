coverage_by_module <- function(
    obj,
    module_label
) {

    observed <- is.finite(
        obj$D_raw_gene
    )

    coverage_cell <- colMeans(
        observed,
        na.rm = TRUE
    )

    dt <- data.table(
        module =
            module_label,

        cell =
            colnames(
                obj$D_raw_gene
            ),

        coverage_fraction =
            coverage_cell
    )

    dt[
        module_cell_scores[
            ,
            .(
                cell,
                group,
                replicate
            )
        ],
        on = "cell",
        `:=`(
            group =
                i.group,
            replicate =
                i.replicate
        )
    ]

    dt
}

