logCP10K_dense <- function(
    count_matrix,
    depth
) {

    x <- as.matrix(
        count_matrix
    )

    x <- sweep(
        x,
        2,
        as.numeric(depth),
        "/"
    )

    x <- x * 10000

    log1p(
        x
    )
}


z_from_stats <- function(
    x,
    feature_ids,
    all_feature_ids,
    mu,
    sd,
    missing_to_zero = FALSE
) {

    jj <- match(
        feature_ids,
        all_feature_ids
    )

    if (anyNA(jj)) {
        stop(
            "Feature IDs absent from preprocessing statistics."
        )
    }

    zz <- sweep(
        x,
        1,
        mu[jj],
        "-"
    )

    good_sd <-
        is.finite(
            sd[jj]
        ) &
        sd[jj] > 0

    if (any(good_sd)) {
        zz[
            good_sd,
        ] <- sweep(
            zz[
                good_sd,
                ,
                drop = FALSE
            ],
            1,
            sd[jj][good_sd],
            "/"
        )
    }

    if (any(!good_sd)) {
        zz[
            !good_sd,
        ] <- 0
    }

    if (missing_to_zero) {
        zz[
            !is.finite(zz)
        ] <- 0
    }

    zz
}


gene_balanced_matrix <- function(
    feature_matrix,
    feature_by_gene,
    genes,
    feature_ids
) {

    out <- matrix(
        NA_real_,
        nrow = length(genes),
        ncol = ncol(feature_matrix),
        dimnames = list(
            genes,
            colnames(feature_matrix)
        )
    )

    feature_lookup <- seq_along(
        feature_ids
    )

    names(feature_lookup) <- as.character(
        feature_ids
    )

    for (g in genes) {

        ids <- feature_by_gene[[g]]

        if (is.null(ids) ||
            length(ids) == 0L) {
            next
        }

        ii <- unname(
            feature_lookup[
                as.character(ids)
            ]
        )

        ii <- ii[
            !is.na(ii)
        ]

        if (length(ii) == 0L) {
            next
        }

        if (length(ii) == 1L) {

            out[
                g,
            ] <- feature_matrix[
                ii,
            ]

        } else {

            out[
                g,
            ] <- colMeans(
                feature_matrix[
                    ii,
                    ,
                    drop = FALSE
                ],
                na.rm = TRUE
            )
        }
    }

    out[
        is.nan(out)
    ] <- NA_real_

    out
}


module_mean_from_gene_matrix <- function(
    gene_matrix
) {

    y <- colMeans(
        gene_matrix,
        na.rm = TRUE
    )

    y[
        is.nan(y)
    ] <- NA_real_

    y
}


rank_biserial <- function(
    x,
    y
) {

    x <- x[
        is.finite(x)
    ]

    y <- y[
        is.finite(y)
    ]

    n1 <- length(x)
    n2 <- length(y)

    if (n1 == 0L || n2 == 0L) {
        return(
            NA_real_
        )
    }

    rr <- rank(
        c(
            x,
            y
        ),
        ties.method = "average"
    )

    U <- sum(
        rr[
            seq_len(n1)
        ]
    ) -
        n1 *
        (
            n1 + 1
        ) /
        2

    2 *
        U /
        (
            n1 *
            n2
        ) -
        1
}


compare_groups <- function(
    values,
    group,
    replicate
) {

    dt <- data.table(
        value =
            as.numeric(
                values
            ),
        group =
            factor(
                as.character(group),
                levels = c(
                    "negative",
                    "positive"
                )
            ),
        replicate =
            factor(
                replicate
            )
    )

    dt <- dt[
        is.finite(value) &
        !is.na(group)
    ]

    xp <- dt[
        group == "positive",
        value
    ]

    xn <- dt[
        group == "negative",
        value
    ]

    if (length(xp) == 0L ||
        length(xn) == 0L) {

        return(
            data.table(
                n_positive = length(xp),
                n_negative = length(xn),
                mean_positive = NA_real_,
                mean_negative = NA_real_,
                delta_mean_pos_minus_neg = NA_real_,
                median_positive = NA_real_,
                median_negative = NA_real_,
                delta_median_pos_minus_neg = NA_real_,
                rank_biserial = NA_real_,
                wilcox_p = NA_real_,
                lm_group_beta_adjusted_replicate = NA_real_,
                lm_group_p_adjusted_replicate = NA_real_
            )
        )
    }

    wt <- suppressWarnings(
        wilcox.test(
            xp,
            xn,
            exact = FALSE
        )
    )

    lm_beta <- NA_real_
    lm_p <- NA_real_

    dt_lm <- dt[
        !is.na(
            replicate
        )
    ]

    if (
        nrow(dt_lm) >= 10L &&
        uniqueN(
            dt_lm$replicate
        ) >= 2L
    ) {

        fit <- lm(
            value ~ group + replicate,
            data = dt_lm
        )

        cc <- summary(
            fit
        )$coefficients

        rn <- rownames(
            cc
        )

        if ("grouppositive" %in% rn) {
            lm_beta <- cc[
                "grouppositive",
                "Estimate"
            ]

            lm_p <- cc[
                "grouppositive",
                "Pr(>|t|)"
            ]
        }
    }

    data.table(
        n_positive =
            length(xp),

        n_negative =
            length(xn),

        mean_positive =
            mean(xp),

        mean_negative =
            mean(xn),

        delta_mean_pos_minus_neg =
            mean(xp) -
            mean(xn),

        median_positive =
            median(xp),

        median_negative =
            median(xn),

        delta_median_pos_minus_neg =
            median(xp) -
            median(xn),

        rank_biserial =
            rank_biserial(
                xp,
                xn
            ),

        wilcox_p =
            wt$p.value,

        lm_group_beta_adjusted_replicate =
            lm_beta,

        lm_group_p_adjusted_replicate =
            lm_p
    )
}


