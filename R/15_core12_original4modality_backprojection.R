# ============================================================
# 17_core12_CELL03_original4modality_validation.R
# GSE303006 / GENCODE M23
#
# Directly validate the two core #12 gene modules in the
# ORIGINAL/NORMALIZED four modalities across CELL03-positive
# versus CELL03-negative cells.
#
# Modules:
#   Positive module:
#     shared leading-edge genes from the positive GO processes
#
#   Negative module:
#     shared leading-edge genes from the negative GO processes
#
# Cells:
#   top 50 U_CELL[,3]  -> CELL03 positive-loading cells
#   bottom 50 U_CELL[,3] -> CELL03 negative-loading cells
#
# E-P mapping:
#   Positive module genes use core #12 E-P pairs with
#       core_EP_score > 0
#
#   Negative module genes use core #12 E-P pairs with
#       core_EP_score < 0
#
# Original observation units are preserved:
#   RNA       : gene x cell
#   ATAC      : enhancer x cell
#   H3K27ac   : enhancer x cell
#   3D        : 20-kb E-P bin-pair x cell
#
# For ATAC/H3/3D, features are first averaged WITHIN each gene,
# then genes are averaged equally. This avoids reintroducing
# E-P degree bias by allowing high-degree genes to dominate.
#
# Measurements:
#   RNA       : logCP10K
#   ATAC      : logCP10K
#   H3K27ac   : logCP10K
#   3D raw    : Euclidean distance and -log(distance)
#   3D z      : Stage-1 standardized -log(distance), missing -> 0
#
# The script reports:
#   - module score differences between CELL03 +/- cells
#   - replicate-adjusted linear-model group effects
#   - positive-module minus negative-module contrasts
#   - gene-level four-modality effects
#   - heatmaps / boxplot PDFs
# ============================================================


