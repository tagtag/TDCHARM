# ============================================================
# 16. Gene-level four-modality effects
#
# For each module gene:
#   RNA gene value
#   mean linked-enhancer ATAC
#   mean linked-enhancer H3K27ac
#   mean linked-binpair 3D proximity
#
# All tests use standardized values; raw group means are also
# reported for direct interpretation.
# ============================================================

gene_level_one_module <- function(
    obj,
    module_label
) {

    genes <- obj$genes

    modality_objects <- list(

        RNA = list(
            raw =
                obj$RNA_raw_gene,
            z =
                obj$RNA_z_gene
        ),

        ATAC = list(
            raw =
                obj$ATAC_raw_gene,
            z =
                obj$ATAC_z_gene
        ),

        H3K27ac = list(
            raw =
                obj$H3_raw_gene,
            z =
                obj$H3_z_gene
        ),

        `3D_proximity` = list(
            raw =
                obj$D_prox_gene,
            z =
                obj$D_z_gene
        )
    )

    ans <- list()
    rr <- 1L

    for (m in names(
        modality_objects
    )) {

        raw_mat <- modality_objects[[m]]$raw

        z_mat <- modality_objects[[m]]$z

        for (g in genes) {

            raw_v <- raw_mat[
                g,
            ]

            z_v <- z_mat[
                g,
            ]

            comp <- compare_groups(
                z_v,
                module_cell_scores$group,
                module_cell_scores$replicate
            )

            posmask <-
                module_cell_scores$group ==
                "positive"

            negmask <-
                module_cell_scores$group ==
                "negative"

            comp[
                ,
                module :=
                    module_label
            ]

            comp[
                ,
                gene_name :=
                    g
            ]

            comp[
                ,
                modality :=
                    m
            ]

            comp[
                ,
                raw_mean_positive :=
                    mean(
                        raw_v[
                            posmask
                        ],
                        na.rm = TRUE
                    )
            ]

            comp[
                ,
                raw_mean_negative :=
                    mean(
                        raw_v[
                            negmask
                        ],
                        na.rm = TRUE
                    )
            ]

            comp[
                ,
                raw_delta_pos_minus_neg :=
                    raw_mean_positive -
                    raw_mean_negative
            ]

            ans[[rr]] <- comp

            rr <- rr + 1L
        }
    }

    out <- rbindlist(
        ans,
        fill = TRUE
    )

    out[
        ,
        FDR_within_module_modality :=
            p.adjust(
                wilcox_p,
                method = "BH"
            ),
        by = modality
    ]

    out
}

gene_level_pos <- gene_level_one_module(
    POS,
    "positive_module"
)

gene_level_neg <- gene_level_one_module(
    NEG,
    "negative_module"
)

