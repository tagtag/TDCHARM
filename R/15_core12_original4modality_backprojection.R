# 12. Gene-balanced modality matrices for each module
# ============================================================

build_module <- function(
    module_name,
    module_genes,
    enh_by_gene,
    bp_by_gene
) {

    genes_use <- intersect(
        module_genes,
        available_genes
    )

    # RNA: one directly observed row per gene.
    RNA_raw_gene <- RNA_log[
        genes_use,
        ,
        drop = FALSE
    ]

    RNA_z_gene <- RNA_z[
        genes_use,
        ,
        drop = FALSE
    ]

    # ATAC/H3: average linked enhancers WITHIN gene.
    ATAC_raw_gene <- gene_balanced_matrix(
        ATAC_log,
        enh_by_gene,
        genes_use,
        selected_enhancers
    )

    ATAC_z_gene <- gene_balanced_matrix(
        ATAC_z,
        enh_by_gene,
        genes_use,
        selected_enhancers
    )

    H3_raw_gene <- gene_balanced_matrix(
        H3_log,
        enh_by_gene,
        genes_use,
        selected_enhancers
    )

    H3_z_gene <- gene_balanced_matrix(
        H3_z,
        enh_by_gene,
        genes_use,
        selected_enhancers
    )

    # 3D: average linked binpairs WITHIN gene.
    D_raw_gene <- gene_balanced_matrix(
        D_raw,
        bp_by_gene,
        genes_use,
        selected_binpairs
    )

    D_prox_gene <- gene_balanced_matrix(
        D_prox,
        bp_by_gene,
        genes_use,
        selected_binpairs
    )

    D_z_gene <- gene_balanced_matrix(
        D_z,
        bp_by_gene,
        genes_use,
        selected_binpairs
    )

    list(
        module_name =
            module_name,

        genes =
            genes_use,

        RNA_raw_gene =
            RNA_raw_gene,

        RNA_z_gene =
            RNA_z_gene,

        ATAC_raw_gene =
            ATAC_raw_gene,

        ATAC_z_gene =
            ATAC_z_gene,

        H3_raw_gene =
            H3_raw_gene,

        H3_z_gene =
            H3_z_gene,

        D_raw_gene =
            D_raw_gene,

        D_prox_gene =
            D_prox_gene,

        D_z_gene =
            D_z_gene
    )
}

